"""Stationary Gaussian random fields on rectangles (FFT filtering) mapped to element centroids."""
import numpy as np
from scipy.interpolate import RegularGridInterpolator


def gaussian_field(x0, x1, y0, y1, corr_len, h, rng):
    """Unit-variance field with squared-exponential correlation exp(-r^2 / corr_len^2).

    Generated by filtering white noise on a padded grid of spacing h; returns an interpolator
    f(points (n,2)) -> values.
    """
    pad = 3.0 * corr_len
    xs = np.arange(x0 - pad, x1 + pad + h, h)
    ys = np.arange(y0 - pad, y1 + pad + h, h)
    noise = rng.standard_normal((ys.size, xs.size))
    kx = np.fft.fftfreq(xs.size, d=h) * 2.0 * np.pi
    ky = np.fft.fftfreq(ys.size, d=h) * 2.0 * np.pi
    KX, KY = np.meshgrid(kx, ky, indexing='xy')
    # square root of the spectral density of exp(-r^2/l^2) is proportional to exp(-k^2 l^2 / 8)
    filt = np.exp(-(KX ** 2 + KY ** 2) * corr_len ** 2 / 8.0)
    field = np.real(np.fft.ifft2(np.fft.fft2(noise) * filt))
    field = (field - field.mean()) / field.std()
    return RegularGridInterpolator((ys, xs), field, bounds_error=False, fill_value=0.0)


def lognormal_property(mean, cov, z):
    """Map standard-normal values z to a lognormal property with given mean and COV."""
    s = np.sqrt(np.log(1.0 + cov ** 2))
    return mean * np.exp(s * z - 0.5 * s ** 2)
